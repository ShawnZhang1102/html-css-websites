                        <h2 id="section1">About <strong>Tesla</strong></h2>

                                <img src="images/Logo.jpg" alt="Logo" width="500" height="500">
                                <!--this is comment-->

                              <p>
                                Tesla, Inc. (/ˈtɛslə/ TESS-lə or /ˈtɛzlə/ TEZ-lə[a]) is an American multinational automotive and clean energy company headquartered in Austin, Texas, which designs and manufactures electric vehicles (cars and trucks), stationary battery energy storage devices from home to grid-scale, solar panels and solar shingles, and related products and services. Its subsidiary Tesla Energy develops and is a major installer of photovoltaic systems in the United States and is one of the largest global suppliers of battery energy storage systems with 6.5 gigawatt-hours (GWh) installed in 2022.
                              </p>
                              <p>
                                Tesla is one of the world's most valuable companies and, as of 2023, is the world's most valuable automaker. In 2022, the company led the battery electric vehicle market, with 18% share.
                              </p>
                              <p>
                                Tesla was incorporated in July 2003 by Martin Eberhard and Marc Tarpenning as Tesla Motors. The company's name is a tribute to inventor and electrical engineer Nikola Tesla. In February 2004, via a $6.5 million investment, Elon Musk became the company's largest shareholder. He became CEO in 2008. Tesla's announced mission is to create products which help "accelerate the world’s transition to sustainable energy."
                              </p>
                              <p>
                                The company began production of its first car model, the Roadster sports car, in 2008. This was followed by the Model S sedan in 2012, the Model X SUV in 2015, the Model 3 sedan in 2017, the Model Y crossover in 2020, the Tesla Semi truck in 2022 and the Cybertruck light-duty pickup truck in 2023. The Model 3 is the all-time bestselling plug-in electric car worldwide, and in June 2021 became the first electric car to sell 1 million units globally. Tesla's 2022 deliveries were around 1.31 million vehicles, a 40% increase over the previous year, and cumulative sales totaled 4 million cars as of April 2023. In October 2021, Tesla's market capitalization temporarily reached $1 trillion, the sixth company to do so in U.S. history.
                              </p> 
                              <p>
                                Tesla has been the subject of lawsuits, government scrutiny, and journalistic criticism, stemming from allegations of whistleblower retaliation, worker rights violations, product defects, and Musk's many controversial statements.
                              </p> 
                              
                        <h2 id="section2"><strong>History</strong></h2>

                        <img src="images/Modles.jpg" alt="Models" height="500" width="700">
                        <div>This this a tesla car </div>
                        <!--this is comment-->

                                <p>The company was incorporated as Tesla Motors, Inc. on July 1, 2003, by Martin Eberhard and Marc Tarpenning. Eberhard and Tarpenning served as CEO and CFO, respectively. Eberhard said that he wanted to build 'a car manufacturer that is also a technology company,' with its core technologies as 'the battery, the computer software, and the proprietary motor'.</p>

                                <p>In May 2010, Tesla purchased what would later become the Tesla Factory in Fremont, California, from Toyota for $42 million, and opened the facility in October 2010 to start production of the Model S. On June 29, 2010, the company went public via an initial public offering (IPO) on the NASDAQ, the first American car company to do so since the Ford Motor Company had its IPO in 1956. The company issued 13.3 million shares of common stock at a price of $17 per share, raising $226 million</p>

                                <p>Tesla entered the solar installation business in November 2016 with the purchase of SolarCity, in an all-stock $2.6 billion deal. The business was merged with Tesla's existing battery energy storage products division to form the Tesla Energy subsidiary. The deal was controversial because at the time of the acquisition, SolarCity was facing liquidity issues of which Tesla's shareholders were not informed. In February 2017, Tesla Motors changed its name to Tesla, Inc. to better reflect the scope of its expanded business.</p>

                                <p>"From July 2019 to June 2020, Tesla reported four consecutive profitable quarters for the first time, which made it eligible for inclusion in the S&P 500. Tesla was added to the index on December 21, 2020. It was the most valuable company ever added, already the sixth-largest member. During 2020, the share price increased 740%, and on January 26, 2021, its market capitalization reached $848 billion, more than the next nine largest automakers combined and becoming the US' 5th most valuable company. In July 2020, Tesla reached a valuation of $206 billion, surpassing Toyota to become the world's most valuable automaker. On August 31, 2020, Tesla completed a 5-for-1 stock split.</p>


                        <h2 id="section3"><strong>Automotive products and services</strong></h2>
                        <p>As of December 2022, Tesla offers five vehicle models: Model S, Model X, Model 3, Model Y, and the Tesla Semi. Tesla's first vehicle, the first-generation Tesla Roadster, is no longer sold. Tesla has plans for a second-generation Roadster and a pickup called the Cybertruck.</p>

                        <h2 id="section4">Models</h2>

                                <ul>
                                        <li>
                                                <h3>Model S</h3>
                                                <p>The Model S is a full-size luxury car with a liftback body style and a dual motor, all-wheel drive layout. Development of the Model S began prior to 2007 and deliveries started in June 2012. The Model S has seen two major design refreshes, first in April 2016 which introduced a new front-end design and again in June 2021 which revised the interior. The Model S was the top-selling plug-in electric car worldwide in 2015 and 2016. Since its introduction, more than 250,000 vehicles have been sold.</p>
                                        </li>
                                        <li>
                                                <h3>Model X</h3>
                                                <p>The Model X is a mid-size luxury crossover SUV offered in 5-, 6-, and 7-passenger configurations with either a dual- or tri-motor, all-wheel drive layout. The rear passenger doors open vertically with an articulating 'falcon-wing' design. A prototype Model X was first shown in February 2012, and deliveries started in September 2015. The Model X shares around 30 percent of its content with the Model S. The vehicle has seen one major design refresh in June 2021, which revised the interior.</p>
                                        </li>
                                        <li>
                                                <h3>Model 3</h3>
                                                <p>The Model 3 is a mid-size car with a fastback body style and either a dual-motor, all-wheel drive layout or a rear-motor, rear-wheel drive layout. The vehicle was designed to be more affordable than the luxury Model S sedan. A prototype Model 3 was first shown in 2016, and within a week, the company received over 325,000 paid reservations. Deliveries started in July 2017. The Model 3 ranked as the world's bestselling electric car from 2018 to 2021, and cumulative sales passed 1 million in June 2021. The vehicle has seen one major design refresh in September 2023, which revised the exterior and interior.</p>
                                        </li>
                                        <li>
                                                <h3>Model Y</h3>
                                                <p>The Model Y is a mid-size crossover SUV offered in 5- and 7-passenger configurations with a dual-motor, all-wheel drive layout. The vehicle was designed to be more affordable than the luxury Model X SUV. A prototype Model Y was first shown in March 2019, and deliveries started in March 2020. The Model Y shared around 75 percent of its content with the Model 3. In the first quarter of 2023, the Model Y outsold the Toyota Corolla to become the world's best-selling car, the first-ever electric vehicle to claim the title.</p>
                                        </li>
                                        <li>
                                                <h3>Tesla Semi</h3>
                                                <p>The Tesla Semi is a Class 8 semi-truck by Tesla, Inc. with a tri-motor, rear-wheel drive layout. Tesla claims that the Semi has approximately three times the power of a typical diesel semi-truck and a range of 500 miles (800 km). Two prototype trucks were first shown in November 2017, and initial deliveries were made to PepsiCo on December 1, 2022. As of July 2023, the truck remains in pilot production, and Tesla does not expect the truck to enter volume production before 2024, due to limited availability of the required 4680 battery cells</p>
                                        </li>
                
                                </ul>
                 

                        <h2 id="section5"><strong>Finances</strong></h2>

                        <p>For the fiscal (and calendar) year 2021, Tesla reported a net income of $5.52 billion. The annual revenue was $53.8 billion, an increase of 71% over the previous fiscal year.</p>
                        <p>Of the revenue number in 2021, $314 million came from selling regulatory credits to other automakers to meet government pollution standards. That number has been a smaller percentage of revenue for multiple quarters.</p>
                        <p>Tesla ended 2021 with $17.6 billion of cash on hand, down $1.8 billion from the end of 2020.</p>
                        <p>In February 2021, a 10-K filing revealed that Tesla had invested some $1.5 billion in the cryptocurrency Bitcoin, and the company indicated it would soon accept Bitcoin as a form of payment. Critics then pointed out how investing in cryptocurrency can run counter to Tesla's environmental goals. Tesla made more profit from the 2021 investment than the profit from selling cars in 2020, due to the Bitcoin price increase after the investment was announced.</p>
                        <p>The quarter ending June 2021 was the first time Tesla made a profit independent of Bitcoin and regulatory credits.</p>
                        
    
