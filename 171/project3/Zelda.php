        <h2>Inspiration</h2>
            <p>The Legend of Zelda was principally inspired by Shigeru Miyamoto's "explorations" as a young boy in the hillsides, forests, and caves surrounding his childhood home in Sonobe, Japan where he ventured into forests with secluded lakes, caves, and rural villages. According to Miyamoto, one of his most memorable experiences was the discovery of a cave entrance in the middle of the woods. After some hesitation, he apprehensively entered the cave, and explored its depths with the aid of a lantern. Miyamoto has referred to the creation of the Zelda games as an attempt to bring to life a "miniature garden" for players to play with in each game of the series.</p>
            <img src="images/Shigeru_Miyamoto_GDC_2007.jpeg" alt="Shigeru">
            <p>The story and setting was developed by Takashi Tezuka. Seeking to create a fairytale adventure game, Tezuka drew inspirations from fantasy books such as J. R. R. Tolkien's The Lord of the Rings. According to Keiji Terui, who wrote the backstory in the first game's manual, the location named Death Mountain was initially a working title for the legend of the Triforce which was written with inspirations from the battles of medieval Europe. The Master Sword was introduced as Excalibur in the French version of A Link to the Past, which originates from the legend of King Arthur in the Welsh collection of Mabinogion. Celtic mythology also inspired the name of Link's steed, Epona, based on the Celtic goddess of fertility.</p>
            
        <h2>Audio</h2>
        
            <p>Games in The Legend of Zelda series frequently feature in-game musical instruments, particularly in musical puzzles, which are widespread. Often, instruments trigger game events: for example, the recorder in The Legend of Zelda can reveal secret areas, as well as warp Link to the Dungeon entrances. This warping with music feature has also been used in A Link to the Past and Link's Awakening. In Ocarina of Time, playing instruments is a core part of the game, with the player needing to play the instrument through the use of the game controller to succeed. Ocarina of Time is "[one of the] first contemporary non-dance title[s] to feature music-making as part of its gameplay", using music as a heuristic device and requiring the player to utilise songs to progress in the game – a game mechanic that is also present in Majora's Mask.</p>
            <img src="images/Koji_Kondo_-_GDC_2007_cropped.jpeg" alt="Koji">   
            <p>"The Legend of Zelda Theme" is a recurring piece of music that was created for the first game of the franchise. The composer and sound director of the series, Koji Kondo, initially planned to use Maurice Ravel's Boléro as the game's title theme, but was forced to change it when he learned, late in the game's development cycle, that the copyright for the orchestral piece had not yet expired. As a result, Kondo wrote a new arrangement of the overworld theme within one day. The "Zelda Theme" has topped ScrewAttack's "Top Ten Videogame Themes Ever" list.</p>
     
        <h2>1986–1997: 2D origins</h2>

            <p>The Legend of Zelda, the first game of the series, was first released in Japan on February 21, 1986, on the Famicom Disk System. A cartridge version for the Nintendo Entertainment System, using battery-backed memory, was released in the United States on August 22, 1987, and in Europe on November 27, 1987. The game features a "Second Quest", accessible either upon completing the game, or by registering one's name as "ZELDA" when starting a new quest. The "Second Quest" features different dungeons and item placement, and more difficult enemies. A modified version of the original Famicom game, BS Zelda no Densetsu, was released for the Super Famicom's satellite-based expansion, Satellaview, on August 6, 1995, in Japan. A second Satellaview game, BS Zelda no Densetsu MAP2 was released for the Satellaview on December 30 the same year. Both games featured rearranged dungeons, an altered overworld, and new voice-acted plot-lines.</p>
            <img src="images/Legend_of_Zelda_NES.png" alt="2D">
            <p>The second game, Zelda II: The Adventure of Link, was released for the Famicom Disk System in Japan on January 14, 1987,[71] and for the Nintendo Entertainment System in Europe in November and North America in December 1988. The game exchanged the top-down perspective for side-scrolling (though the top-down point of view was retained for overworld areas), and introduced RPG elements (such as experience points) not used previously or thereafter in the series. The Legend of Zelda and Zelda II were released in gold-colored cartridges instead of the console's regular grey cartridges. Both were re-released in the final years of the Nintendo Entertainment System with grey cartridges.</p>

        <h2>1998–2001: Transition to 3D</h2>

            <p>After five years without a new game, the series made the transition to 3D with Ocarina of Time for the Nintendo 64, which was released in November 1998. This game, initially known as Zelda 64, retains the core gameplay of the previous 2D games, and was very successful commercially and critically, considered by many critics and gamers to be the best video game of all time, and ranking highly on IGN and EGM's "greatest games of all time" lists, as well as scoring perfect scores in several video game publications. In February 2006, it was ranked by Nintendo Power as the best game released for a Nintendo console. The game was originally developed for the poorly selling, Japanese-only 64DD, but was converted to cartridge format when the 64DD hardware was delayed.</p>
            <img src="images/ZELDA_OCARINA_OF_TIME_2.jpeg" alt="1998">
            <p>A new gameplay mechanic, lock-on targeting, is used in the game, which focuses the camera on a nearby target and alters the player's actions relative to that target. Such mechanics allow precise sword fighting in a 3D space. The game heavily uses context-sensitive button play, which enabled the player to control various actions with Link using only one button on the Nintendo 64's controller. Each action was handled slightly differently but all used the 'A' button to perform. For instance, standing next to a block and pressing 'A' made Link grab it (enabling him to push/pull it), but moving forwards into a block and pressing 'A' allowed Link to climb the block. The game featured the first appearance of Link's horse, Epona, allowing Link to travel quickly across land and fire arrows from horseback. Those who preordered the game received a gold-colored cartridge in a limited edition box with a golden plastic card affixed, reading "Collector's Edition". In some stores that had this "Collector's Edition" quickly sell out, a small and rare Zelda pin was given instead. It is the sword and shield emblem with "Zelda" written on it.
            </p>

        <h2>2002–2005: Introduction of Toon Link and multiplayer</h2>

            <p>The Game Boy Advance release of A Link to the Past in 2002 featured a new game, Four Swords, the first multiplayer Zelda. This game introduced Toon Link, a name first used in Super Smash Bros. Brawl to refer to cartoon-based visual designs of Link. Four Swords Anniversary Edition was released on September 28, 2011, as free DSiWare available until February 20, 2012.</p>
            <img src="images/The_Legend_of_Zelda_The_Wind_Waker_screenshot.jpeg" alt="02">
            <p>When Nintendo revealed the GameCube on August 24, 2000, the day before Nintendo's Space World 2000 exposition, a software demonstration showed a realistically styled real-time duel between Ganondorf and Link. Fans and the media speculated that the battle might be from a Zelda game in development at the time. At Space World 2001, Nintendo showed a cel-shaded Zelda game, later released as The Wind Waker in December 2002. Due to poor reception, nothing further was shown until a playable demonstration was ready. Miyamoto felt The Wind Waker would "extend Zelda's reach to all ages". The gameplay centers on controlling wind with a baton called the "Wind Waker" and sailing a small boat around an island-filled ocean, retaining similar gameplay mechanics as the previous 3D games in the series. The Legend of Zelda: Collector's Edition, released for the GameCube in 2003, included the original The Legend of Zelda, Zelda II, Ocarina of Time, Majora's Mask, and a demo of The Wind Waker. The Legend of Zelda: The Wind Waker HD was released for Wii U in 2013.</p>

        <h2>2006–2011: Motion and touch-based swordplay</h2>

            <p>In November 2006, Twilight Princess was released as the first Zelda game on the Wii, and later in December as the last Nintendo-published game for the GameCube, the console for which it was originally developed. The Wii version features motion controls and a reversed world where everything that is in the west on the GameCube is in the east on the Wii. The display is mirrored in order to make Link right-handed to make use of the Wii Remote feel more natural for the majority of players. The game chronicles the struggle of a young adult Link to confront the troubles of the "Twilight Realm", a mysterious force that appears around and interacts with Hyrule. When he enters this realm, he is transformed into a wolf, and loses the ability to use his sword, shield or other items, but gains other abilities such as sharpened senses from his new form. Twilight Princess includes an incarnation of Link's horse, Epona, for fast transportation, and features mounted battle scenarios including boss battles that were not seen in previous games. Twilight Princess diverted from the cel-shading of Wind Waker, integrating graphics featuring more detailed textures, giving the game a darker atmosphere. The Legend of Zelda: Twilight Princess HD released for Wii U in 2016.</p>
            <img src="images/Zelda_-_Twilight_Princess_-_stab.jpeg" alt="2006">

        <h2>2013–present: Open-world emphasisz</h2>

            <p>In 2013, Nintendo released The Legend of Zelda: A Link Between Worlds for the Nintendo 3DS, a sequel to A Link to the Past. Progression is more open-ended than previous titles, with the possibility of completing many of the game's dungeons in any order. Certain dungeon obstacles require the use of rented or purchased items. The Legend of Zelda: Tri Force Heroes, a cooperative multiplayer game, was released for the 3DS in October 2015. It features the same Link as A Link Between Worlds but lacks open-world gameplay.</p>
