        <h2>Background information</h2>

            <img src="images/zelda.png" alt="ZELDA">

            <p><strong>The Legend of Zelda is an action-adventure game franchise created by the Japanese game designers Shigeru Miyamoto and Takashi Tezuka.</strong> It is primarily developed and published by Nintendo, although some portable installments and re-releases have been outsourced to Flagship, Vanpool, and Grezzo. The gameplay incorporates action-adventure and elements of action RPG games.</p>
        
            <p>The series centers on the various incarnations of Link, a courageous young man of the elf-like Hylian race, and Princess Zelda, a magical princess who is the mortal reincarnation of the goddess Hylia, as they fight to save the magical land of Hyrule from Ganon, an evil warlord turned demon king, who is the principal antagonist of the series.</p>

            <p>Ganon wishes to use the Triforce, a sacred relic left behind by the three goddesses that created Hyrule, to remake the world in his own dark image. When gathered together, the power of the Triforce can grant any wish its user desires; however, if someone with a heart that does not possess a balance of the three virtues of Power, Courage, and Wisdom attempts to touch the Triforce, it will split into three triangles and bond with three people whose hearts embody the required virtue.</P>

            <img src="images/Link_250px.jpeg" alt="Link">

            <p>Although their personalities and backstory differ from game to game, the incarnations of Link and Zelda often have many traits in common, such as Link often being left-handed and clad in green, and Zelda being associated with wisdom, light, and prophesy. While the conflict with Ganon serves as a backbone for the series, some games have featured other settings and antagonists, with Link traveling or being sent to these other lands in their time of need.</p>
