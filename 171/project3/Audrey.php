      <h2><strong>About Audley Hepburn</strong></h2>
      <p><strong>Audrey Kathleen Hepburn</strong> (née Ruston; 4 May 1929 – 20 January 1993) was a British[a] actress. Recognized as a film and fashion icon, she was ranked by the American Film Institute as the third-greatest female screen legend from the Classical Hollywood cinema and was inducted into the International Best Dressed Hall of Fame List.</p>
      <p><strong>Born in Ixelles, Brussels</strong>, to an aristocratic family, Hepburn spent parts of her childhood in Belgium, England, and the Netherlands. She attended boarding school in Kent, England, from 1936 to 1939. With the outbreak of World War II, she returned to the Netherlands.[3] During the war, she studied ballet at the Arnhem Conservatory, and by 1944, she performed ballet to raise money to support the Dutch resistance.[4] She studied ballet with Sonia Gaskell in Amsterdam beginning in 1945, and with Marie Rambert in London from 1948. She began performing as a chorus girl in West End musical theatre productions and then had minor appearances in several films. She rose to stardom in the romantic comedy Roman Holiday (1953) alongside Gregory Peck, for which she was the first actress to win an Oscar, a Golden Globe Award, and a BAFTA Award for a single performance. That year, she also won a Tony Award for Best Lead Actress in a Play for her performance in Ondine.</p>
      <p><strong>Hepburn</strong> went on to star in a number of successful films such as Sabrina (1954), in which Humphrey Bogart and William Holden compete for her affection; Funny Face (1957), a musical in which she sang her own parts; the drama The Nun's Story (1959); the romantic comedy Breakfast at Tiffany's (1961); the thriller-romance Charade (1963), opposite Cary Grant; and the musical My Fair Lady (1964). In 1967, she starred in the thriller Wait Until Dark, receiving Academy Award, Golden Globe, and BAFTA nominations. After that, she only occasionally appeared in films, one being Robin and Marian (1976) with Sean Connery. Her last recorded performances were in the 1990 documentary television series Gardens of the World with Audrey Hepburn for which she won a Primetime Emmy Award for Outstanding Individual Achievement – Informational Programming.</p>

      <h2><strong>Humanitarian Works</strong></h2>
      <p><em>Hepburn's mother, Baroness Ella van Heemstra (12 June 1900 – 26 August 1984), was a Dutch noblewoman. Ella was the daughter of Baron Aarnoud van Heemstra, who served as mayor of Arnhem from 1910 to 1920 and as governor of Dutch Guiana from 1921 to 1928, and Baroness Elbrig Willemine Henriette van Asbeck (1873–1939), a granddaughter of Count Dirk van Hogendorp.[9] At age 19, she married Jonkheer Hendrik Gustaaf Adolf Quarles van Ufford, an oil executive based in Batavia, Dutch East Indies, where they subsequently lived.[10] They had two sons, Jonkheer Arnoud Robert Alexander Quarles van Ufford (1920–1979) and Jonkheer Ian Edgar Bruce Quarles van Ufford (1924–2010), before divorcing in 1925,[11][12] four years before Hepburn's birth.[7]</em></p>
      <p>Hepburn's father, Joseph Victor Anthony Ruston (21 November 1889 – 16 October 1980), was a British subject born in Auschitz, Bohemia, Austria-Hungary.[13] He was the son of Victor John George Ruston, of British and Austrian background,[14] and Anna Juliana Franziska Karolina Wels, who was of Austrian origin and born in Kovarce.[15] In 1923–1924, Joseph was an Honorary British Consul in Semarang in the Dutch East Indies,[16] and prior to his marriage to Hepburn's mother, was married to Cornelia Bisschop, a Dutch heiress.[13][11] He later changed his surname to the more "aristocratic" double-barrelled Hepburn-Ruston, perhaps at Ella's insistence,[17] as he mistakenly believed himself descended from James Hepburn, third husband of Mary, Queen of Scots.[b][14][11]</p>
      <p>Hepburn's parents were married in Batavia, Dutch East Indies, in September 1926.[10] At the time, Ruston worked for a trading company, but soon after the marriage, the couple moved to Europe, where he began working for a loan company; reportedly tin merchants MacLaine, Watson and Company in London.[8] After a year in London, they moved to Brussels, where he had been assigned to open a branch office.[10][19] After three years spent travelling between Brussels, Arnhem, The Hague and London, the family settled in the suburban Brussels municipality of Linkebeek in 1932.[10][20] Hepburn's early childhood was sheltered and privileged.[10] Her multinational background was enhanced by the family's travelling between three countries due to her father's job.[21][c]</p>

      <h2><strong>Personal Life</strong></h2>
      <figure><img src="images/Audrey_Hepburn_screentest_in_Roman_Holiday_trailer.jpg" alt="Audrey_Hepburn_screentest_in_Roman_Holiday_trailer"></figure>
      <figcaption>Figure 2</figcaption>
      <p><em>In August 1988</em>, Hepburn went to Turkey on an immunization campaign. She called Turkey "the loveliest example" of UNICEF's capabilities. Of the trip, she said, "The army gave us their trucks, the fishmongers gave their wagons for the vaccines, and once the date was set, it took ten days to vaccinate the whole country. Not bad."[106] In October, Hepburn went to South America. Of her experiences in Venezuela and Ecuador, Hepburn told the United States Congress, "I saw tiny mountain communities, slums, and shantytowns receive water systems for the first time by some miracle – and the miracle is UNICEF. I watched boys build their own schoolhouse with bricks and cement provided by UNICEF."[108]</p>
      <p><em>Hepburn toured Central America in February 1989</em>, and met with leaders in Honduras, El Salvador, and Guatemala. In April, she visited Sudan with Wolders as part of a mission called "Operation Lifeline". Because of civil war, food from aid agencies had been cut off. The mission was to ferry food to southern Sudan. Hepburn said, "I saw but one glaring truth: These are not natural disasters but man-made tragedies for which there is only one man-made solution – peace."[106] In October 1989, Hepburn and Wolders went to Bangladesh. John Isaac, a UN photographer, said, "Often the kids would have flies all over them, but she would just go hug them. I had never seen that. Other people had a certain amount of hesitation, but she would just grab them. Children would just come up to hold her hand, touch her – she was like the Pied Piper."[10]</p>

      <h2><strong>Final Years</strong></h2>
      <p>From 1980 until her death, Hepburn was in a relationship with Dutch actor Robert Wolders, the widower of actress Merle Oberon.[39] She had met Wolders through a friend during the later years of her second marriage. In 1989, she called the nine years she had spent with him the happiest years of her life, and stated that she considered them married, just not officially.[128]</p>

